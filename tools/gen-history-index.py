#!/usr/bin/env python3
"""Build the history reference indexes under docs/reference/history/.

Run from anywhere:
    python tools/gen-history-index.py [NAME=MIRROR_GIT_DIR ...]

Sources:
  - docs/currentstate.md and docs/currentstate/*.md: every dated "## " entry.
  - docs/plans/**/*.md: one row per plan with its first H1 title.
  - local archive/* branches of this repository: commits not on main.
  - optional mirror clones of retired nested llama.cpp forks (NAME=PATH):
    commits on each local branch that no remote-tracking ref contains.

Every table is generated. The verdict and signal columns only repeat words
that already appear in a source heading or commit subject. Nothing here is
hand-edited; rerun the script instead.
"""
import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference" / "history"

VERDICT = re.compile(
    r"\b(DONE|CLOSED|ACCEPTED|REJECTED|REFUTED|FALSIFIED|FAILED|FAILS|FAIL|PASS|"
    r"NO-GO|REVERTED|PARKED|DEFERRED|ABORTED|ABORT|SUPERSEDED|WITHDRAWN|DROPPED|"
    r"REFUSED|UNCERTIFIED|GO)\b"
)
SIGNAL = re.compile(
    r"(?i)\b(opt-in|default off|falsif\w*|refut\w*|revert\w*|reject\w*|no-go|"
    r"fail\w*|accept\w*|park\w*|abandon\w*|drop\w*|supersed\w*|regress\w*|"
    r"speed\w*|faster|slower|win\w*)\b"
)
DATE = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")
SKIP_HEADING = re.compile(r"^(How this file|Recent entries|Index|Known gaps|Blocked|Completed)", re.I)


def git(repo, *args):
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        capture_output=True, text=True, encoding="utf-8", errors="replace", check=True,
    ).stdout


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ").strip()


def write(name, lines):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/reference/history/{name} ({len(lines)} lines)")


def currentstate_rows():
    files = [ROOT / "docs" / "currentstate.md"] + sorted((ROOT / "docs" / "currentstate").glob("*.md"))
    rows = []
    for f in files:
        for i, line in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if not line.startswith("## "):
                continue
            title = line[3:].strip()
            if SKIP_HEADING.match(title) or "archived entries" in title:
                continue
            m = DATE.search(title)
            if not m:
                continue
            verdicts = sorted(set(VERDICT.findall(title)))
            rows.append((m.group(1), verdicts, title, f.relative_to(ROOT).as_posix(), i))
    rows.sort(key=lambda r: (r[0], r[3], -r[4]), reverse=True)
    return rows


def build_currentstate():
    rows = currentstate_rows()
    lines = [
        "# Current-state entries (generated)",
        "",
        "Generated by `tools/gen-history-index.py` from `docs/currentstate.md` and",
        "`docs/currentstate/*.md`. Newest first. The entry text is in the source file",
        "at the line shown. Verdict words are copied from the heading.",
        "",
        f"Entries: {len(rows)}",
        "",
        "| Date | Verdict words | Entry heading | Source |",
        "|---|---|---|---|",
    ]
    for date, verdicts, title, path, line_no in rows:
        lines.append(f"| {date} | {' '.join(verdicts) or '-'} | {cell(title[:260])} | `{path}:{line_no}` |")
    write("currentstate-entries.md", lines)


def build_plans():
    rows = []
    for p in git(ROOT, "ls-files", "docs/plans").splitlines():
        f = ROOT / p
        if f.suffix.lower() in (".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf"):
            rows.append((p, f.suffix.lower(), "(binary)", 0))
            continue
        text = f.read_text(encoding="utf-8", errors="replace").splitlines()
        if f.suffix.lower() == ".md":
            title = next((l[2:].strip() for l in text[:60] if l.startswith("# ")), "")
        else:
            title = next((l.strip() for l in text[:20] if l.strip()), "")
        rows.append((p, f.suffix.lower() or "-", title, len(text)))
    lines = [
        "# Plans and specifications (generated)",
        "",
        "Generated by `tools/gen-history-index.py` from every tracked file under",
        "`docs/plans/`. Title is the first H1 of a Markdown file, or the first",
        "non-empty line of any other file.",
        "",
        f"Files: {len(rows)}",
        "",
        "| File | Type | Title | Lines |",
        "|---|---|---|---|",
    ]
    for p, kind, title, n in rows:
        lines.append(f"| `{p}` | {kind} | {cell(title[:200])} | {n} |")
    write("plans.md", lines)


def build_outer_archive():
    lines = [
        "# Archived branches in this repository (generated)",
        "",
        "Generated by `tools/gen-history-index.py`. For each `archive/*` branch, the",
        "commits that are not on `main`. These are the experiment branches that were",
        "consolidated from the old folders.",
        "",
    ]
    for ref in git(ROOT, "for-each-ref", "--format=%(refname:short)", "refs/heads/archive/").split():
        commits = git(ROOT, "log", "main..%s" % ref, "--date=short", "--format=%h%x09%ad%x09%s").splitlines()
        lines.append(f"## `{ref}` ({len(commits)} commits not on main)")
        lines.append("")
        lines.append("| Commit | Date | Subject | Signal |")
        lines.append("|---|---|---|---|")
        for c in commits:
            h, d, s = (c.split("\t") + ["", "", ""])[:3]
            sig = " ".join(sorted({m.group(0).lower() for m in SIGNAL.finditer(s)}))
            lines.append(f"| `{h}` | {d} | {cell(s)} | {sig or '-'} |")
        lines.append("")
    write("outer-archive-branches.md", lines)


def build_nested(name, mirror):
    lines = [
        f"# Nested llama.cpp fork: {name} (generated)",
        "",
        "Generated by `tools/gen-history-index.py` from a mirror clone of the retired",
        "nested fork. A commit is listed once, under the first local branch that",
        "reaches it, and only if no remote-tracking ref (upstream ggml-org history) contains it.",
        "",
    ]
    seen = set()
    rows = []
    for br in git(mirror, "for-each-ref", "--format=%(refname:short)", "refs/heads/").split():
        for c in git(mirror, "log", br, "--not", "--remotes", "--date=short", "--format=%h%x09%ad%x09%s").splitlines():
            h, d, s = (c.split("\t") + ["", "", ""])[:3]
            if h in seen:
                continue
            seen.add(h)
            sig = " ".join(sorted({m.group(0).lower() for m in SIGNAL.finditer(s)}))
            rows.append((br, h, d, s, sig))
    lines.append(f"Local-only commits: {len(rows)}")
    lines.append("")
    lines.append("| Branch | Commit | Date | Subject | Signal |")
    lines.append("|---|---|---|---|---|")
    for br, h, d, s, sig in rows:
        lines.append(f"| `{br}` | `{h}` | {d} | {cell(s)} | {sig or '-'} |")
    write(f"nested-{name}.md", lines)


def build_readme(nested_names):
    lines = [
        "# History reference (generated indexes)",
        "",
        "These files are produced by `tools/gen-history-index.py`. Rerun the script",
        "after new entries are added, instead of editing the tables.",
        "",
        "- `currentstate-entries.md`: every dated entry in the current-state record.",
        "- `plans.md`: every plan and specification file under `docs/plans/`.",
        "- `outer-archive-branches.md`: experiment branches consolidated into this repo.",
    ]
    for n in nested_names:
        lines.append(f"- `nested-{n}.md`: commits of a retired nested llama.cpp fork (kept as bundles under `archive/source-repos/`).")
    write("README.md", lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("nested", nargs="*", help="NAME=MIRROR_GIT_DIR of a retired nested fork")
    args = ap.parse_args()
    build_currentstate()
    build_plans()
    build_outer_archive()
    names = []
    for spec in args.nested:
        name, _, mirror = spec.partition("=")
        build_nested(name, mirror)
        names.append(name)
    build_readme(names)


if __name__ == "__main__":
    main()
